<script setup>
import { ref, computed, onMounted } from 'vue'
import { useRoute, useRouter } from 'vue-router'
import UserNavbar from '@/components/UserNavbar.vue'
import GameService from '@/services/GameService'
import { userAuthStore } from '@/stores/auth'

const route = useRoute()
const router = useRouter()
const authStore = userAuthStore()
const gameId = route.params.id

const game = ref(null)
const isLoading = ref(true)
const isStarting = ref(false)
const flagInput = ref('')
const flagMessage = ref('')
const challenges = ref([])

const difficultyColor = (name) => {
  const c = challenges.value.find(ch => ch.name === name)
  if (!c) return '#6B7280'
  if (c.difficulty <= 1) return '#00C853'
  if (c.difficulty === 2) return '#FCD34D'
  return '#DC0B00'
}

const difficultyLabel = (name) => {
  const c = challenges.value.find(ch => ch.name === name)
  if (!c) return 'Unknown'
  if (c.difficulty <= 1) return 'Easy'
  if (c.difficulty === 2) return 'Medium'
  return 'Hard'
}

const currentUsername = computed(() => {
  const user = authStore.currentUser
  return user?.username ?? user?.player ?? null
})

const isCreator = computed(() => {
  return game.value?.created_by?.player === currentUsername.value
})

const isStarted = computed(() => {
  return game.value?.started_at != null
})

const teams = computed(() => {
  return game.value?.team_list ?? []
})

const fetchGame = async () => {
  isLoading.value = true
  try {
    const response = await GameService.getGame(gameId)
    game.value = response.data
  } catch (error) {
    console.error('Failed to fetch game:', error)
  } finally {
    isLoading.value = false
  }
}

const startGame = async () => {
  if (!confirm('Are you sure you want to start the game? This cannot be undone.')) return
  isStarting.value = true
  try {
    const response = await GameService.startGame(gameId)
    game.value = response.data
  } catch (error) {
    console.error('Failed to start game:', error)
  } finally {
    isStarting.value = false
  }
}

const submitFlag = () => {
  if (!flagInput.value.trim()) return
  flagMessage.value = `Flag "${flagInput.value.trim()}" submitted.`
  flagInput.value = ''
  setTimeout(() => { flagMessage.value = '' }, 3000)
}

const downloadConfig = () => {
  const content = `# WireGuard config for ${game.value?.name}\n# Generated by Hack & Seek\n`
  const blob = new Blob([content], { type: 'text/plain' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `game${gameId}.cfg`
  a.click()
  URL.revokeObjectURL(url)
}

// ─── Helpers (for running view) ─────────────────────────────────────────────

const statusClass = (status) => {
  if (status === 'secured') return 'bg-[#00C853]/10 border-[#00C853]/30 text-[#00C853]'
  if (status === 'defeated') return 'bg-[#DC0B00]/10 border-[#DC0B00]/30 text-[#DC0B00]'
  return 'bg-gray-700/30 border-gray-600 text-gray-400'
}

const rowClass = (status) => {
  if (status === 'secured') return 'bg-[#00C853]/5 border-l-4 border-l-[#00C853]'
  if (status === 'defeated') return 'bg-[#DC0B00]/5 border-l-4 border-l-[#DC0B00]'
  return 'border-l-4 border-l-transparent'
}

// Strip the "_gameN" suffix from team names for display
const displayTeamName = (name) => {
  return name?.split('_game')[0] ?? name
}

onMounted(async () => {
  fetchGame()
  try {
    const res = await GameService.getChallenges()
    challenges.value = res.data
  } catch (e) {}
})
</script>

<template>
  <div class="min-h-screen">
    <UserNavbar />

    <!-- Loading -->
    <div v-if="isLoading" class="max-w-4xl mx-auto px-4 py-16 text-center text-gray-500">
      Loading game...
    </div>

    <!-- Game not found -->
    <div v-else-if="!game" class="max-w-4xl mx-auto px-4 py-16 text-center text-gray-500">
      Game not found.
    </div>

    <div v-else class="max-w-4xl mx-auto px-4 py-8 space-y-8">

      <!-- ── Header (shared) ────────────────────────────────────────────── -->
      <div class="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div class="flex items-center gap-4">
          <button
            @click="router.back()"
            class="secondary-button flex items-center gap-2"
          >
            ← Back
          </button>
          <h1 class="text-4xl font-bold text-[#E0E6F0]">{{ game.name }}</h1>
          <span
            :class="[
              'text-xs font-semibold px-2 py-1 rounded-md border',
              isStarted
                ? 'bg-[#00C853]/10 border-[#00C853]/30 text-[#00C853]'
                : 'bg-[#FCD34D]/10 border-[#FCD34D]/30 text-[#FCD34D]'
            ]"
          >
            {{ isStarted ? 'Running' : 'Pending' }}
          </span>
        </div>
        <button v-if="isStarted" @click="downloadConfig" class="primary-button flex items-center gap-2">
          <svg xmlns="http://www.w3.org/2000/svg" class="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M4 16v1a2 2 0 002 2h12a2 2 0 002-2v-1M12 4v12m0 0l-4-4m4 4l4-4" />
          </svg>
          Download game{{ gameId }}.cfg
        </button>
      </div>

      <!-- ════════════════════════════════════════════════════════════════ -->
      <!-- ── LOBBY VIEW (game not started) ─────────────────────────────── -->
      <!-- ════════════════════════════════════════════════════════════════ -->
      <template v-if="!isStarted">

        <!-- Teams Overview -->
        <div class="bg-[#1F2937] rounded-2xl overflow-hidden">
          <div class="px-6 py-4 border-b border-gray-700">
            <h2 class="text-2xl font-bold text-[#E0E6F0]">Teams</h2>
          </div>

          <div v-if="teams.length === 0" class="px-6 py-8 text-center text-gray-500">
            No teams configured.
          </div>

          <div v-else class="divide-y divide-gray-800">
            <div
              v-for="team in teams"
              :key="team.name"
              class="px-6 py-5 space-y-3"
            >
              <div class="flex items-center justify-between">
                <h3 class="text-lg font-semibold text-[#E0E6F0]">{{ displayTeamName(team.name) }}</h3>
                <span
                  class="text-xs font-semibold px-2 py-1 rounded-md border"
                  :style="{ color: difficultyColor(team.challenge), borderColor: difficultyColor(team.challenge) + '4D', backgroundColor: difficultyColor(team.challenge) + '1A' }"
                >
                  {{ team.challenge }} · {{ difficultyLabel(team.challenge) }}
                </span>
              </div>
              <div class="flex flex-wrap gap-2">
                <span
                  v-for="member in team.team_members"
                  :key="member.player"
                  class="bg-[#0F172A] text-[#E0E6F0] text-xs px-3 py-1 rounded-md border border-gray-700"
                >
                  {{ member.player }}
                </span>
                <span v-if="!team.team_members || team.team_members.length === 0" class="text-xs text-gray-600 italic">
                  No players
                </span>
              </div>
            </div>
          </div>
        </div>

        <!-- Start Game Button (creator only) -->
        <div v-if="isCreator" class="flex justify-center pt-4">
          <button
            @click="startGame"
            :disabled="isStarting"
            class="primary-button text-lg px-10 py-3 font-bold"
          >
            {{ isStarting ? 'Starting...' : 'Start Game' }}
          </button>
        </div>
        <div v-else class="text-center text-gray-500 text-sm pt-4">
          Waiting for the game creator to start the game...
        </div>

      </template>

      <!-- ════════════════════════════════════════════════════════════════ -->
      <!-- ── RUNNING VIEW (game started) ──────────────────────────────── -->
      <!-- ════════════════════════════════════════════════════════════════ -->
      <template v-else>

        <!-- ── Flag Submission ──────────────────────────────────────────── -->
        <div class="bg-[#1F2937] rounded-2xl overflow-hidden">
          <div class="px-6 py-4 border-b border-gray-700">
            <h2 class="text-2xl font-bold text-[#E0E6F0]">Submit Flag</h2>
          </div>
          <div class="px-6 py-5">
            <div class="flex gap-3">
              <input
                v-model="flagInput"
                type="text"
                placeholder="FLAG{...}"
                @keyup.enter="submitFlag"
                class="flex-grow bg-[#0F172A] border border-gray-700 rounded-lg px-4 py-3 text-[#E0E6F0] font-mono focus:ring-2 focus:ring-[#00C853] focus:border-transparent outline-none transition-all"
              />
              <button @click="submitFlag" class="primary-button px-6">Submit</button>
            </div>
            <p v-if="flagMessage" class="mt-3 text-sm text-[#00C853]">{{ flagMessage }}</p>
          </div>
        </div>

        <!-- ── Leaderboard ────────────────────────────────────────────── -->
        <div class="bg-[#1F2937] rounded-2xl overflow-hidden">
          <div class="px-6 py-4 border-b border-gray-700 flex items-center justify-between">
            <h2 class="text-2xl font-bold text-[#E0E6F0]">Leaderboard</h2>
            <div class="flex items-center gap-4 text-xs text-gray-500">
              <span class="flex items-center gap-1"><span class="w-2 h-2 rounded-full bg-[#00C853] inline-block"></span> Secured</span>
              <span class="flex items-center gap-1"><span class="w-2 h-2 rounded-full bg-[#DC0B00] inline-block"></span> Defeated</span>
              <span class="flex items-center gap-1"><span class="w-2 h-2 rounded-full bg-gray-500 inline-block"></span> Active</span>
            </div>
          </div>

          <!-- Table Header -->
          <div class="grid grid-cols-12 px-6 py-3 bg-[#0F172A] text-xs font-semibold text-gray-500 uppercase tracking-wider">
            <span class="col-span-1">#</span>
            <span class="col-span-5">Team</span>
            <span class="col-span-3">Challenge</span>
            <span class="col-span-3 text-right">Points</span>
          </div>

          <!-- Rows from real team data -->
          <div
            v-for="(team, idx) in teams"
            :key="team.name"
            class="grid grid-cols-12 items-center px-6 py-4 border-b border-gray-800 transition-colors border-l-4 border-l-transparent"
            :class="idx % 2 === 0 ? 'bg-[#0F172A]/40' : ''"
          >
            <span :class="['col-span-1 font-bold text-lg', idx === 0 ? 'text-[#FCD34D]' : 'text-gray-500']">
              {{ idx + 1 }}
            </span>
            <span class="col-span-5 font-semibold text-[#E0E6F0]">{{ displayTeamName(team.name) }}</span>
            <span class="col-span-3 text-sm font-semibold" :style="{ color: difficultyColor(team.challenge) }">{{ team.challenge }}</span>
            <span :class="['col-span-3 text-right font-bold text-base', idx === 0 ? 'text-[#FCD34D]' : 'text-[#E0E6F0]']">
              0 pts
            </span>
          </div>

          <div v-if="teams.length === 0" class="px-6 py-8 text-center text-gray-500">
            No teams in this game.
          </div>
        </div>

        <!-- ── Defeat Log ──────────────────────────────────────────────── -->
        <div class="bg-[#1F2937] rounded-2xl overflow-hidden">
          <div class="px-6 py-4 border-b border-gray-700">
            <h2 class="text-2xl font-bold text-[#E0E6F0]">Defeat Log</h2>
          </div>
          <div class="px-6 py-8 text-center text-gray-500 text-sm">
            No captures yet.
          </div>
        </div>

      </template>
    </div>
  </div>
</template>

