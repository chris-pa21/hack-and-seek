<script setup>
import { useRoute, useRouter } from 'vue-router'
import UserNavbar from '@/components/UserNavbar.vue'

const route = useRoute()
const router = useRouter()
const gameId = route.params.id

// ─── Mocked Data ──────────────────────────────────────────────────────────────

const game = {
  id: gameId,
  name: `Game #${gameId}`,
}

// status: 'default' | 'secured' | 'defeated'
const leaderboard = [
  { rank: 1, team: 'Team Alpha', challenge: 'Challenge 2', status: 'secured',  points: 420 },
  { rank: 2, team: 'Team Delta', challenge: 'Challenge 1', status: 'default',  points: 310 },
  { rank: 3, team: 'Team Beta',  challenge: 'Challenge 3', status: 'defeated', points: 180 },
  { rank: 4, team: 'Team Gamma', challenge: 'Challenge 1', status: 'defeated', points: 90  },
].sort((a, b) => b.points - a.points)

const defeatLog = [
  { attacker: 'Team Alpha', defender: 'Team Beta',  points: 150, time: '11:42' },
  { attacker: 'Team Alpha', defender: 'Team Gamma', points: 120, time: '11:58' },
  { attacker: 'Team Delta', defender: 'Team Beta',  points: 80,  time: '12:05' },
  { attacker: 'Team Gamma', defender: 'Team Delta', points: 60,  time: '12:19' },
]

// ─── WireGuard Config Download ─────────────────────────────────────────────────

const downloadConfig = () => {
  const content = `# WireGuard config for ${game.name}\n# Generated by Hack & Seek\n`
  const blob = new Blob([content], { type: 'text/plain' })
  const url  = URL.createObjectURL(blob)
  const a    = document.createElement('a')
  a.href     = url
  a.download = `game${gameId}.cfg`
  a.click()
  URL.revokeObjectURL(url)
}

// ─── Helpers ───────────────────────────────────────────────────────────────────

const statusClass = (status) => {
  if (status === 'secured')  return 'bg-[#00C853]/10 border-[#00C853]/30 text-[#00C853]'
  if (status === 'defeated') return 'bg-[#DC0B00]/10 border-[#DC0B00]/30 text-[#DC0B00]'
  return 'bg-gray-700/30 border-gray-600 text-gray-400'
}

const rowClass = (status) => {
  if (status === 'secured')  return 'bg-[#00C853]/5 border-l-4 border-l-[#00C853]'
  if (status === 'defeated') return 'bg-[#DC0B00]/5 border-l-4 border-l-[#DC0B00]'
  return 'border-l-4 border-l-transparent'
}
</script>

<template>
  <div class="min-h-screen">
    <UserNavbar />

    <div class="max-w-4xl mx-auto px-4 py-8 space-y-8">

      <!-- ── Header ─────────────────────────────────────────────────────── -->
      <div class="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div class="flex items-center gap-4">
          <button
            @click="router.back()"
            class="secondary-button flex items-center gap-2"
          >
            ← Back
          </button>
          <h1 class="text-4xl font-bold text-[#E0E6F0]">{{ game.name }}</h1>
        </div>
        <button @click="downloadConfig" class="primary-button flex items-center gap-2">
          <svg xmlns="http://www.w3.org/2000/svg" class="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M4 16v1a2 2 0 002 2h12a2 2 0 002-2v-1M12 4v12m0 0l-4-4m4 4l4-4" />
          </svg>
          Download game{{ gameId }}.cfg
        </button>
      </div>

      <!-- ── Leaderboard ────────────────────────────────────────────────── -->
      <div class="bg-[#1F2937] rounded-2xl overflow-hidden">
        <div class="px-6 py-4 border-b border-gray-700 flex items-center justify-between">
          <h2 class="text-2xl font-bold text-[#E0E6F0]">Leaderboard</h2>
          <div class="flex items-center gap-4 text-xs text-gray-500">
            <span class="flex items-center gap-1"><span class="w-2 h-2 rounded-full bg-[#00C853] inline-block"></span> Secured</span>
            <span class="flex items-center gap-1"><span class="w-2 h-2 rounded-full bg-[#DC0B00] inline-block"></span> Defeated</span>
            <span class="flex items-center gap-1"><span class="w-2 h-2 rounded-full bg-gray-500 inline-block"></span> Active</span>
          </div>
        </div>

        <!-- Table Header -->
        <div class="grid grid-cols-12 px-6 py-3 bg-[#0F172A] text-xs font-semibold text-gray-500 uppercase tracking-wider">
          <span class="col-span-1">#</span>
          <span class="col-span-4">Team</span>
          <span class="col-span-3">Challenge</span>
          <span class="col-span-2">Status</span>
          <span class="col-span-2 text-right">Points</span>
        </div>

        <!-- Rows -->
        <div
          v-for="(entry, idx) in leaderboard"
          :key="entry.team"
          :class="['grid grid-cols-12 items-center px-6 py-4 border-b border-gray-800 transition-colors', rowClass(entry.status), idx % 2 === 0 ? 'bg-[#0F172A]/40' : '']"
        >
          <!-- Rank -->
          <span :class="['col-span-1 font-bold text-lg', idx === 0 ? 'text-[#FCD34D]' : 'text-gray-500']">
            {{ idx + 1 }}
          </span>
          <!-- Team -->
          <span class="col-span-4 font-semibold text-[#E0E6F0]">{{ entry.team }}</span>
          <!-- Challenge -->
          <span class="col-span-3 text-sm text-gray-400">{{ entry.challenge }}</span>
          <!-- Status chip -->
          <span class="col-span-2">
            <span :class="['text-xs font-semibold px-2 py-1 rounded-md border', statusClass(entry.status)]">
              {{ entry.status === 'secured' ? '🛡 Secured' : entry.status === 'defeated' ? '💀 Defeated' : '⚔ Active' }}
            </span>
          </span>
          <!-- Points -->
          <span :class="['col-span-2 text-right font-bold text-base', idx === 0 ? 'text-[#FCD34D]' : 'text-[#E0E6F0]']">
            {{ entry.points }} pts
          </span>
        </div>
      </div>

      <!-- ── Defeat Log ──────────────────────────────────────────────────── -->
      <div class="bg-[#1F2937] rounded-2xl overflow-hidden">
        <div class="px-6 py-4 border-b border-gray-700">
          <h2 class="text-2xl font-bold text-[#E0E6F0]">Defeat Log</h2>
        </div>
        <div class="divide-y divide-gray-800">
          <div
            v-for="(event, idx) in defeatLog"
            :key="idx"
            class="flex items-center gap-4 px-6 py-4 text-sm"
          >
            <span class="text-gray-600 shrink-0 font-mono text-xs w-12">{{ event.time }}</span>
            <span class="text-2xl">🏴</span>
            <p class="flex-1">
              <span class="font-bold text-[#E0E6F0]">{{ event.attacker }}</span>
              <span class="text-gray-400"> captured </span>
              <span class="font-bold text-[#DC0B00]">{{ event.defender }}</span>
            </p>
            <span class="text-[#00C853] font-bold shrink-0">+{{ event.points }} pts</span>
          </div>
        </div>
      </div>

    </div>
  </div>
</template>

